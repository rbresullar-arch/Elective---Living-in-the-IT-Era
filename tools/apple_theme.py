def convert_rule(m):
    sel, body = m.group(1), m.group(2)
    if 'var(--display)' in body:
        body = re.sub(r'font-weight:\s*400', 'font-weight:700', body)
        if 'font-weight' not in body:
            body += ';font-weight:700'
        body = re.sub(r'letter-spacing:\s*[\d.]+px', 'letter-spacing:-.02em', body)
    if 'var(--pixel)' in body:
        if 'font-weight' not in body:
            body += ';font-weight:600'
        body = re.sub(r'letter-spacing:\s*[\d.]+px', 'letter-spacing:.03em', body)
    return sel + '{' + body + '}'


def convert_css(css):
    if '/* apple-converted */' in css:
        return css
    css = re.sub(r'(?:\d+(?:\.\d+)?)px (solid|dashed) var\(--ink\)', r'1px \1 var(--hair)', css)
    css = re.sub(r'border-(left|right|top|bottom):\s*\d+px solid var\(--hair\)', r'border-\1:.5px solid var(--hair)', css)
    css = re.sub(r'box-shadow:\s*0 \d+px 0 var\(--ink\)', 'box-shadow:var(--sh-1)', css)
    css = re.sub(r'([^{}]+)\{([^{}]*)\}', convert_rule, css)
    return '/* apple-converted */\n' + css


def apply(path, acc, ink='#FFFFFF', extra='', fx=True):
    p = pathlib.Path(path)
    s = p.read_text(encoding='utf-8')
    # fonts
    s = re.sub(r'<link[^>]+fonts\.googleapis\.com/css2[^>]*>', '<!--apple-font-->', s, count=1)
    s = re.sub(r'<link rel="preconnect"[^>]+>\s*', '', s)
    s = s.replace('<!--apple-font-->', '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
                  '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n' + FONT_LINK, 1)
    # own stylesheet (first <style>, not the theme one)
    m = re.search(r'<style>(.*?)</style>', s, re.S)
    if m:
        s = s[:m.start(1)] + convert_css(m.group(1)) + s[m.end(1):]
    # theme style
    theme = '<style id="apple-theme">' + THEME % {'sf': SF, 'acc': acc, 'ink': ink} + extra + '\n</style>\n'
    s = re.sub(r'<style id="apple-theme">.*?</style>\n?', '', s, flags=re.S)
    s = s.replace('</head>', theme + '</head>', 1)
    # shader script
    s = re.sub(r'\n?<script id="apple-fx">.*?</script>\n?', '\n', s, flags=re.S)
    if fx:
        s = s.replace('</body>', FX.strip() + '\n</body>', 1)
    p.write_text(s, encoding='utf-8')


if __name__ == '__main__':
    a = sys.argv
    extra = pathlib.Path(a[4]).read_text(encoding='utf-8') if len(a) > 4 else ''
    apply(a[1], a[2], a[3] if len(a) > 3 else '#FFFFFF', extra, fx=not (len(a) > 5 and a[5] == 'nofx'))
